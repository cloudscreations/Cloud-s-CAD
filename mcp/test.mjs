import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import fs from 'node:fs';
const t = new StdioClientTransport({ command: 'node', args: ['dist/clouds-cad-mcp.mjs'] });
const c = new Client({ name: 't', version: '1' });
await c.connect(t);
console.log((await c.listTools()).tools.map((x) => x.name).join(', '));
const call = async (name, args) => { const r = await c.callTool({ name, arguments: args }); console.log(`--- ${name}${r.isError ? ' [ERROR]' : ''}\n` + r.content[0].text); return r; };
fs.rmSync('/tmp/mcpt', { recursive: true, force: true }); fs.mkdirSync('/tmp/mcpt');
const F = '/tmp/clouds-cad/real_freecad.dxf';
await call('check_dxf', { dxf_path: F });
await call('dxf_to_tap', { dxf_path: F, output_path: '/tmp/mcpt/a.tap' });
await call('dxf_to_tap', { dxf_path: F, output_path: '/tmp/mcpt/a.tap' });
await call('dxf_to_tap', { dxf_path: F, output_path: '/tmp/mcpt/b.tap', fit_width_in: 3, start_x: 0, start_y: 0 });
await call('tap_info', { tap_path: '/tmp/mcpt/a.tap' });
await call('tap_to_dxf', { tap_path: '/tmp/clouds-cad/sample_machine.tap', output_path: '/tmp/mcpt/s.dxf' });
await call('check_dxf', { dxf_path: '/tmp/clouds-cad/out/two_shapes.dxf' });
await call('dxf_to_tap', { dxf_path: '/tmp/clouds-cad/out/two_shapes.dxf', output_path: '/tmp/mcpt/m.tap' });
await call('dxf_to_tap', { dxf_path: '/nope.dxf' });
await call('machine_format_help', {});
await c.close();
