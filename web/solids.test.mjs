import { setKernelLoader, revolveLoops, sweepLoops, loftLoops, roundEdges, shellModel, offsetModel, addHole, signedVolume, SCREWS } from './solids.js';
import { extrudeLoops } from './mesh.js';
import Module from 'manifold-3d';
setKernelLoader(async()=>{const w=await Module();w.setup();return w;});
const sq=(x,y,w,h)=>[[x,y],[x+w,y],[x+w,y+h],[x,y+h]];
const near=(a,b,t,n)=>{if(Math.abs(a-b)>t*Math.abs(b)){console.log('FAIL',n,a,b);process.exitCode=1}else console.log('ok',n,a.toFixed(1))};
let r=await revolveLoops([sq(5,0,5,10)],{segments:128});
near(Math.abs(signedVolume(r)),Math.PI*(100-25)*10,0.01,'revolve');
let s=await sweepLoops([sq(-2,-2,4,4)],[[0,0],[50,0]]);
near(Math.abs(signedVolume(s)),16*50,0.01,'sweep straight');
let s2=await sweepLoops([sq(-2,-2,4,4)],[[0,0],[50,0],[50,50]]);
console.log('sweep L vol',Math.abs(signedVolume(s2)));
let l=await loftLoops(sq(0,0,20,20),sq(0,0,10,10),{height:10});
near(Math.abs(signedVolume(l)),10/3*(400+100+200),0.03,'loft');
const box=extrudeLoops([sq(0,0,20,20)],10);
let rr=await roundEdges(box,2); console.log('round vol',signedVolume(rr),'<',4000);
let sh=await shellModel(box,2); console.log('shell vol',signedVolume(sh));
let sho=await shellModel(box,2,{openTop:true}); console.log('cup vol',signedVolume(sho));
let of=await offsetModel(box,1); console.log('offset',signedVolume(of));
let h=await addHole(box,{x:10,y:10,dia:5}); near(Math.abs(signedVolume(h)),4000-Math.PI*6.25*10,0.01,'hole');
